//! The push API's bearer token, in a file of its own.
//!
//! Deliberate exception to the "secrets only in Credential Manager" rule
//! (`credential.rs`): the token exists so a *script* can authenticate with one
//! line — `Get-Content island_api_token.txt` — and a script cannot read
//! Credential Manager without the same ceremony as writing a Win32 program.
//! The file is still per-user (`%LOCALAPPDATA%`), the API binds 127.0.0.1 only,
//! and the token grants exactly one capability: posting cards to the island.
//!
//! Why not `[api] token` inside `island.toml`: the island writes only the `ui`
//! table (`patch_ui`) and the settings centre merge-writes everything else
//! while preserving disk `ui` — a token generated by the island inside the
//! TOML would be clobbered by the next settings save. A separate file has one
//! writer at a time (island creates, settings resets) and the server re-reads
//! it by mtime, so a reset takes effect without a restart.

use std::path::PathBuf;
use std::time::SystemTime;

const BCRYPT_USE_SYSTEM_PREFERRED_RNG: u32 = 0x0000_0002;

#[link(name = "bcrypt")]
extern "system" {
    /// `hAlgorithm` is null with `BCRYPT_USE_SYSTEM_PREFERRED_RNG`; the status
    /// is an NTSTATUS (non-negative = success), not a BOOL.
    fn BCryptGenRandom(algorithm: isize, buffer: *mut u8, len: u32, flags: u32) -> i32;
}

pub fn path() -> PathBuf {
    super::local_dir().join("island_api_token.txt")
}

/// The current token, if the file exists and is non-empty. Whitespace is
/// trimmed so a hand-edited trailing newline does not break authentication.
pub fn read() -> Option<String> {
    read_at(&path())
}

pub fn read_at(p: &std::path::Path) -> Option<String> {
    let text = std::fs::read_to_string(p).ok()?;
    let text = text.trim();
    if text.is_empty() || text.len() > 256 {
        return None;
    }
    Some(text.to_string())
}

/// Read the token, creating it on first use. Called by the island when the
/// API starts; the settings centre only ever calls [`read`] or [`reset`].
pub fn ensure() -> Result<String, String> {
    if let Some(t) = read() {
        return Ok(t);
    }
    let token = generate()?;
    write(&token)?;
    Ok(token)
}

/// Replace the token (settings centre "重置"). The running server picks the
/// new value up by mtime; no restart, no config write.
pub fn reset() -> Result<String, String> {
    let token = generate()?;
    write(&token)?;
    Ok(token)
}

fn write(token: &str) -> Result<(), String> {
    // Atomic swap for the same reason as the TOML: a half-written token read
    // by a script mid-reset would authenticate against nothing.
    dcx_win32::config_file::write_atomic(&path(), token.as_bytes())
        .map_err(|e| format!("写入 token 失败：{e}"))
}

fn generate() -> Result<String, String> {
    let mut bytes = [0u8; 32];
    let status = unsafe {
        BCryptGenRandom(
            0,
            bytes.as_mut_ptr(),
            bytes.len() as u32,
            BCRYPT_USE_SYSTEM_PREFERRED_RNG,
        )
    };
    if status < 0 {
        return Err(format!("BCryptGenRandom 失败：NTSTATUS {status:#x}"));
    }
    let mut hex = String::with_capacity(64);
    for b in bytes {
        hex.push(char::from_digit((b >> 4) as u32, 16).unwrap_or('0'));
        hex.push(char::from_digit((b & 0xf) as u32, 16).unwrap_or('0'));
    }
    Ok(hex)
}

/// File mtime, for the server's re-read cache.
pub fn stamp() -> Option<SystemTime> {
    std::fs::metadata(path()).and_then(|m| m.modified()).ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generated_tokens_are_64_hex_chars_and_unique() {
        let a = generate().unwrap();
        let b = generate().unwrap();
        assert_eq!(a.len(), 64);
        assert!(a.chars().all(|c| c.is_ascii_hexdigit()));
        assert_ne!(a, b);
    }

    #[test]
    fn read_trims_and_rejects_empty() {
        let dir = std::env::temp_dir().join(format!("dcx-api-token-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let p = dir.join("token.txt");
        std::fs::write(&p, "  abc123 \n").unwrap();
        assert_eq!(read_at(&p).as_deref(), Some("abc123"));
        std::fs::write(&p, "   ").unwrap();
        assert_eq!(read_at(&p), None);
        let _ = std::fs::remove_file(&p);
        let _ = std::fs::remove_dir(&dir);
    }
}