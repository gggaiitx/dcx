//! Give `dcx-box.exe` its **own** icon and a version block.
//!
//! The box is a separate application from the platform host: Explorer, the
//! taskbar and the file-properties dialog read this icon from the PE resource
//! section, long before any of our code runs. It deliberately uses `box.ico`,
//! not `dcx.ico`, so the two executables are distinguishable at a glance.
//!
//! The icon has to live in the PE resource section: Explorer, the taskbar and
//! the file-properties dialog all read it from disk, long before any of our
//! code runs. `Icon::from_rgba` cannot help there — that only covers windows we
//! create ourselves.
//!
//! The workspace deliberately carries no build-dependency crates, so instead of
//! pulling in `embed-resource`/`winres` (which would drag in `toml`, `serde`,
//! `winreg`, ...) this script finds the Windows SDK's `rc.exe` directly, writes
//! a small `.rc` describing the icon, compiles it to `.res`, and hands that to
//! link.exe via `cargo:rustc-link-arg-bins`.
//!
//! If the SDK (or `rc.exe`) is missing, the build still succeeds without an
//! icon: a plain `cargo build` on a machine without VS should not fail over
//! cosmetics.

use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

fn main() {
    println!("cargo:rerun-if-changed=build.rs");

    // Read at *run* time: cargo only sets this for the script's execution, not
    // while compiling the script itself.
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let ico = manifest.join("../../brand/box.ico");
    println!("cargo:rerun-if-changed={}", ico.display());

    if !ico.exists() {
        println!(
            "cargo:warning=box icon missing ({}); run tools/gen_brand.py — building without it",
            ico.display()
        );
        return;
    }

    let Some(rc_exe) = find_rc() else {
        println!(
            "cargo:warning=rc.exe (Windows SDK) not found; dcx-box.exe will ship without its icon"
        );
        return;
    };

    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    let rc_file = out_dir.join("box.rc");
    let res_file = out_dir.join("box.res");

    if let Err(err) = std::fs::write(&rc_file, resource_script(&ico)) {
        println!("cargo:warning=cannot write {}: {err}", rc_file.display());
        return;
    }

    let compiled = Command::new(&rc_exe)
        .arg("/nologo")
        .arg("/fo")
        .arg(&res_file)
        .arg(&rc_file)
        .stdout(Stdio::null())
        .status();

    match compiled {
        Ok(status) if status.success() && res_file.exists() => {
            // Hand the .res to the linker as an *input file*, not as `/RES:`:
            // link.exe only recognises `.res`/`.obj`/`.lib` by extension and
            // warns LNK4044 "unrecognized option" for `/RES:path`. Bins only —
            // the injected DLLs have no business carrying this resource.
            println!("cargo:rustc-link-arg-bins={}", res_file.display());
        }
        Ok(status) => {
            println!("cargo:warning=rc.exe exited {status}; dcx-box.exe will ship without its icon")
        }
        Err(err) => println!("cargo:warning=cannot run {}: {err}", rc_exe.display()),
    }
}

/// The resource script. Written at build time rather than checked in so the
/// absolute path to the `.ico` never needs escaping by hand and the version
/// numbers cannot drift from `Cargo.toml`.
fn resource_script(ico: &Path) -> String {
    let ico = ico.display().to_string().replace('\\', "\\\\");
    let version = std::env::var("CARGO_PKG_VERSION").unwrap_or_else(|_| "0.0.0".to_owned());
    let mut parts = version.split('.').map(|p| {
        p.split(['-', '+'])
            .next()
            .unwrap_or("0")
            .parse::<u32>()
            .unwrap_or(0)
    });
    let (major, minor, patch) = (
        parts.next().unwrap_or(0),
        parts.next().unwrap_or(0),
        parts.next().unwrap_or(0),
    );
    let quad = format!("{major},{minor},{patch},0");

    format!(
        r#"// generated by build.rs — do not edit
1 ICON "{ico}"

1 VERSIONINFO
 FILEVERSION {quad}
 PRODUCTVERSION {quad}
 FILEFLAGSMASK 0x3fL
 FILEFLAGS 0x0L
 FILEOS 0x40004L
 FILETYPE 0x1L
 FILESUBTYPE 0x0L
BEGIN
  BLOCK "StringFileInfo"
  BEGIN
    BLOCK "040904b0"
    BEGIN
      VALUE "CompanyName", "DCX"
      VALUE "FileDescription", "DCX desktop file box"
      VALUE "FileVersion", "{version}"
      VALUE "InternalName", "dcx-box"
      VALUE "LegalCopyright", "MIT License"
      VALUE "OriginalFilename", "dcx-box.exe"
      VALUE "ProductName", "DCX"
      VALUE "ProductVersion", "{version}"
    END
  END
  BLOCK "VarFileInfo"
  BEGIN
    VALUE "Translation", 0x409, 1200
  END
END
"#
    )
}

/// `rc.exe` ships with the Windows SDK. A developer prompt usually has it on
/// `PATH`; otherwise pick the newest version installed under `Windows Kits`.
fn find_rc() -> Option<PathBuf> {
    let on_path = Command::new("rc.exe")
        .arg("/?")
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status();
    if on_path.is_ok() {
        return Some(PathBuf::from("rc.exe"));
    }

    let kits = std::env::var_os("ProgramFiles(x86)")
        .or_else(|| std::env::var_os("ProgramFiles"))
        .map(PathBuf::from)?;

    let mut found: Vec<PathBuf> = std::fs::read_dir(kits.join("Windows Kits/10/bin"))
        .ok()?
        .filter_map(|entry| entry.ok())
        .map(|entry| entry.path().join("x64").join("rc.exe"))
        .filter(|candidate| candidate.is_file())
        .collect();
    // Version directories sort lexically, so the last one is the newest SDK.
    found.sort();
    found.pop()
}
